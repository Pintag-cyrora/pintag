// scripts/image-integrity.py -- orphan classification (renditions vs genuine orphans). Run with:
//   node --test image-integrity.test.js
//
// Three layers:
//   1. image_integrity_lib.py rendition-name parsing is pinned to the REAL image-renditions.js (renditionPath), so a
//      rendition can be mapped back to its original reliably and the two implementations cannot drift apart.
//   2. classify() per category: referenced original, valid rendition, orphaned rendition (several reasons), unregistered
//      unit-type image, agent photo, genuine orphan, malformed rendition name.
//   3. The REAL script end to end against a fake `psql`: exit code, report content, strictness, and that the connection
//      string never reaches the output.
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createRequire } from 'node:module';
import { execFileSync, spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const ROOT = path.dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const R = require('./image-renditions.js');

function py(code, input) {
  return JSON.parse(execFileSync('python3', ['-I', '-c', 'import sys,json;sys.path.insert(0,sys.argv[1]);import image_integrity_lib as L;d=json.load(sys.stdin);' + code, path.join(ROOT, 'scripts')],
    { input: JSON.stringify(input), encoding: 'utf8' }));
}
const classify = (o) => py('print(json.dumps(L.classify(d["objects"],d["registry_all"],d["registry_active"],d["listing_refs"],d["unit_refs"],d["agent_refs"])))',
  Object.assign({ objects: [], registry_all: [], registry_active: [], listing_refs: [], unit_refs: [], agent_refs: [] }, o));
const R_ = (name, profile = 'hero') => R.renditionPath(name, profile);

test('rendition names generated by image-renditions.js parse back to the same stem + profile (all 4 profiles)', () => {
  const names = ['1787301675902-4gcl6e.jpg', '1787301675902-4gcl6e.JPG', 'a.b.c.jpeg', 'agents/ab12/1700000000.png', 'no-extension', '1700-my photo (1).jpg'];
  const cases = [];
  for (const n of names) for (const prof of Object.keys(R.PT_RENDITION_PROFILES)) cases.push([R_(n, prof), R.renditionStem(n), prof]);
  const out = py('print(json.dumps([[L.parse_rendition(c[0]), L.rendition_stem(c[3])] for c in d]))',
    cases.map((c, i) => [...c, names[Math.floor(i / 4)]]));
  out.forEach(([parsed, pyStem], i) => {
    assert.deepEqual(parsed, [cases[i][1], cases[i][2]], cases[i][0]);
    assert.equal(pyStem, cases[i][1], 'python rendition_stem == JS renditionStem for ' + cases[i][0]);
  });
});

test('the profile list in the checker equals the profiles image-renditions.js produces', () => {
  assert.deepEqual(py('print(json.dumps(list(L.PROFILES)))', {}).sort(), Object.keys(R.PT_RENDITION_PROFILES).sort());
});

test('name_from_url mirrors the registry extraction (greedy prefix strip, query dropped, external URLs ignored)', () => {
  const U = 'https://x.supabase.co/storage/v1/object/public/property-images/';
  const out = py('print(json.dumps([L.name_from_url(u) for u in d]))',
    [U + 'a.jpg', U + 'a.jpg?width=400', U + 'agents/1/2.jpg', 'https://scontent.fbcdn.net/x.jpg', '', null]);
  assert.deepEqual(out, ['a.jpg', 'a.jpg', 'agents/1/2.jpg', null, null, null]);
});

test('classify: referenced original + its valid renditions are accounted for (listing, unit-type and registry sources)', () => {
  const r = classify({
    objects: ['a.jpg', R_('a.jpg', 'hero'), R_('a.jpg', 'card'), 'u.jpg', R_('u.jpg', 'thumbnail')],
    registry_all: ['a.jpg'], registry_active: ['a.jpg'], listing_refs: ['a.jpg'], unit_refs: ['u.jpg'],
  });
  assert.equal(r.mapped, 1);
  assert.deepEqual(r.categories.rendition_ok, [R_('a.jpg', 'card'), R_('a.jpg', 'hero'), R_('u.jpg', 'thumbnail')].sort());
  assert.deepEqual(r.categories.unit_image_unregistered, ['u.jpg']);
  for (const k of ['orphan_rendition', 'orphan_original', 'rendition_malformed', 'listing_ref_unregistered']) assert.deepEqual(r.categories[k], [], k);
});

test('classify: renditions are orphaned when the original is removed, unreferenced, or missing -- each with its reason', () => {
  const r = classify({
    objects: ['gone.jpg', R_('gone.jpg'), 'loose.jpg', R_('loose.jpg'), R_('ghost.jpg'), 'live.jpg', R_('live.jpg')],
    registry_all: ['gone.jpg', 'live.jpg'], registry_active: ['live.jpg'],   // gone.jpg: status removed
  });
  assert.deepEqual(r.categories.orphan_rendition, [R_('gone.jpg'), R_('ghost.jpg'), R_('loose.jpg')].sort());
  assert.match(r.reasons[R_('gone.jpg')], /removed from its gallery/);
  assert.match(r.reasons[R_('loose.jpg')], /nothing references it/);
  assert.match(r.reasons[R_('ghost.jpg')], /not found in storage/);
  assert.deepEqual(r.categories.rendition_ok, [R_('live.jpg')]);
  assert.deepEqual(r.categories.orphan_original, ['loose.jpg']);   // loose.jpg itself is a genuine orphan too
});

test('classify: genuine orphaned originals, malformed rendition-folder names and drifted listing refs stay failing categories', () => {
  const r = classify({
    objects: ['stray.jpg', 'renditions/x/huge.webp', 'renditions/x/hero.png', 'renditions/hero.webp', 'drift.jpg'],
    listing_refs: ['drift.jpg'],
  });
  assert.deepEqual(r.categories.orphan_original, ['stray.jpg']);
  assert.deepEqual(r.categories.rendition_malformed, ['renditions/hero.webp', 'renditions/x/hero.png', 'renditions/x/huge.webp']);
  assert.deepEqual(r.categories.listing_ref_unregistered, ['drift.jpg']);
});

test('classify: a rendition is NOT excused by another rendition, and an unrelated stem prefix does not match', () => {
  const r = classify({
    objects: ['a.jpg', 'ab.jpg', R_('ab.jpg')], registry_all: ['a.jpg'], registry_active: ['a.jpg'],
  });
  assert.deepEqual(r.categories.orphan_rendition, [R_('ab.jpg')]);                  // "ab" != "a"
  assert.deepEqual(r.categories.orphan_original, ['ab.jpg']);
});

test('classify: a reference that is itself a rendition path never excuses another rendition (no stem is derived from a rendition)', () => {
  const weird = 'renditions/x/hero.webp';            // e.g. a gallery URL accidentally pointing at a rendition
  const r = classify({ objects: [R_(weird)], listing_refs: [weird], registry_all: [], registry_active: [] });
  assert.deepEqual(r.categories.orphan_rendition, [R_(weird)]);
});

test('classify: agent photos are accepted only when parties.photo_url actually references them', () => {
  const r = classify({ objects: ['agents/1/1.jpg', 'agents/2/2.jpg', R_('agents/1/1.jpg')], agent_refs: ['agents/1/1.jpg'] });
  assert.deepEqual(r.categories.agent_photo, ['agents/1/1.jpg']);
  assert.deepEqual(r.categories.orphan_original, ['agents/2/2.jpg']);
  assert.deepEqual(r.categories.rendition_ok, [R_('agents/1/1.jpg')]);
});

// ── end to end: the real script, a fake psql ────────────────────────────────
const SECRET = 'postgres://ro_user:S3cr3tPassw0rd@db.example.invalid:5432/postgres';
function runScript(fixture, extraArgs = []) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'iicheck-'));
  fs.writeFileSync(path.join(dir, 'fixture.json'), JSON.stringify(fixture));
  fs.writeFileSync(path.join(dir, 'psql'), `#!/usr/bin/env node
const fx = JSON.parse(require('fs').readFileSync(process.env.FIXTURE, 'utf8'));
const sql = process.argv[process.argv.length - 1];
process.stdout.write(JSON.stringify(sql.includes("'objects'") ? fx.refs : fx.metrics) + '\\n');
`, { mode: 0o755 });
  const res = spawnSync('python3', [path.join(ROOT, 'scripts', 'image-integrity.py'), ...extraArgs], {
    env: { ...process.env, PATH: dir + path.delimiter + process.env.PATH, FIXTURE: path.join(dir, 'fixture.json'), PINTAG_PROD_DB_URL: SECRET },
    encoding: 'utf8',
  });
  fs.rmSync(dir, { recursive: true, force: true });
  return res;
}
const METRICS = { listings: 2, registered: 2, registered_all: 3, storage_objects: 9, hash_coverage: 1, missing_files: 0,
  invalid_property: 0, listings_missing_images: 0, cover_wrong: 0, cover_not_first: 0 };
const REFS_OK = { objects: ['a.jpg', 'b.jpg', R_('a.jpg'), R_('b.jpg', 'card'), 'u.jpg', R_('u.jpg')],
  registry_all: ['a.jpg', 'b.jpg'], registry_active: ['a.jpg', 'b.jpg'], listing_refs: ['a.jpg', 'b.jpg'], unit_refs: ['u.jpg'], agent_refs: [] };

test('script: renditions of referenced originals + unit images pass; hash coverage is a NOTE, not a failure; no secret in output', () => {
  const r = runScript({ metrics: METRICS, refs: REFS_OK });
  assert.equal(r.status, 0, r.stdout + r.stderr);
  assert.match(r.stdout, /STATUS: HEALTHY/);
  assert.match(r.stdout, /Orphaned files:\s+0/);
  assert.match(r.stdout, /Renditions of referenced originals \(accounted for\): 3/);
  assert.match(r.stdout, /Unit-type images not in the registry \(known gap\): 1/);
  assert.match(r.stdout, /Hash coverage:\s+1 \/ 2/);
  assert.match(r.stdout, /NOTE \(not pass\/fail\): 1 registered image\(s\) have no sha256/);
  assert.ok(!(r.stdout + r.stderr).includes('S3cr3tPassw0rd') && !(r.stdout + r.stderr).includes('db.example.invalid'));
});

test('script: orphaned renditions and genuine orphans FAIL, with counts and representative paths', () => {
  const refs = { ...REFS_OK, objects: [...REFS_OK.objects, R_('removed.jpg'), 'stray.jpg', 'renditions/x/bad.webp'], registry_all: [...REFS_OK.registry_all, 'removed.jpg'] };
  const r = runScript({ metrics: METRICS, refs });
  assert.equal(r.status, 1);
  assert.match(r.stdout, /STATUS: FAILED/);
  assert.match(r.stdout, /Orphaned files:\s+3/);
  assert.match(r.stdout, /ORPHANED renditions .*: 1 \[FAILS\]/);
  assert.match(r.stdout, new RegExp('renditions/removed/hero\\.webp\\s+<- original was removed from its gallery'));
  assert.match(r.stdout, /ORPHANED originals .*: 1 \[FAILS\]\s+stray\.jpg/);
  assert.match(r.stdout, /unrecognised name: 1 \[FAILS\]/);
  assert.match(r.stderr, /3 orphaned object\(s\)/);
  assert.ok(!(r.stdout + r.stderr).includes('S3cr3tPassw0rd'));
});

test('script: --fail-on-unit-images makes the unit-image gap fail; --allow-orphans still tolerates N', () => {
  assert.equal(runScript({ metrics: METRICS, refs: REFS_OK }, ['--fail-on-unit-images']).status, 1);
  const refs = { ...REFS_OK, objects: [...REFS_OK.objects, 'stray.jpg'] };
  assert.equal(runScript({ metrics: METRICS, refs }).status, 1);
  assert.equal(runScript({ metrics: METRICS, refs }, ['--allow-orphans', '1']).status, 0);
});

test('script: every other anomaly still fails exactly as before (missing file)', () => {
  const r = runScript({ metrics: { ...METRICS, missing_files: 1 }, refs: REFS_OK });
  assert.equal(r.status, 1);
  assert.match(r.stderr, /1 missing file/);
});
