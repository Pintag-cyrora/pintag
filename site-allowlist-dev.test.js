// The development mirror (deploy-dev.yml -> Pintag-cyrora/pintag-dev + its Pages site) uses the same deploy allowlist as production, with the development configuration
// and without the production CNAME. Run with: node --test site-allowlist-dev.test.js
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { build, listFiles, parseManifest, ROOT } from './scripts/build-site.mjs';

const MANIFEST = fs.readFileSync(path.join(ROOT, 'site-manifest.txt'), 'utf8');
const M = parseManifest(MANIFEST);
const tmp = () => fs.mkdtempSync(path.join(os.tmpdir(), 'devsite-'));
const prodOut = tmp(), devOut = tmp();
const prod = build({ out: prodOut, version: 'abcd1234' });
const dev = build({ out: devOut, version: 'abcd1234', env: 'dev' });
const WF = fs.readFileSync(path.join(ROOT, '.github/workflows/deploy-dev.yml'), 'utf8');
const ref = (f) => (fs.readFileSync(path.join(ROOT, f), 'utf8').match(/https:\/\/([a-z0-9]+)\.supabase\.co/) || [])[1];

test('both builds succeed, and the development output is the production output minus CNAME', () => {
  assert.deepEqual(prod.errors, []); assert.deepEqual(dev.errors, []);
  const p = listFiles(prodOut), d = listFiles(devOut);
  assert.ok(p.includes('CNAME')); assert.ok(!d.includes('CNAME'));
  assert.deepEqual(d, p.filter((f) => f !== 'CNAME'));
});

test('config.js in the development output is config.dev.js and mentions no production project (and vice versa)', () => {
  assert.equal(fs.readFileSync(path.join(devOut, 'config.js'), 'utf8'), fs.readFileSync(path.join(ROOT, 'config.dev.js'), 'utf8'));
  assert.equal(fs.readFileSync(path.join(prodOut, 'config.js'), 'utf8'), fs.readFileSync(path.join(ROOT, 'config.prod.js'), 'utf8'));
  const prodRef = ref('config.prod.js'), devRef = ref('config.dev.js');
  assert.ok(prodRef && devRef && prodRef !== devRef);
  // the pages' Content-Security-Policy <meta> lists both projects' hosts (generated by scripts/apply-csp.mjs, identical in production); nothing else may name the production project
  const noCsp = (t) => t.replace(/<meta http-equiv="Content-Security-Policy"[^>]*>/g, '');
  for (const f of listFiles(devOut)) if (/\.(html|js|css)$/.test(f)) assert.ok(!noCsp(fs.readFileSync(path.join(devOut, f), 'utf8')).includes(prodRef), `${f} mentions the production project outside its CSP`);
});

test('nothing outside the allowlist can reach the development mirror (same guarantees as production)', () => {
  const out = listFiles(devOut);
  const bad = out.filter((f) => /^(docs|tests|scripts|supabase|ops|cloudflare-worker|pintag-studio|node_modules|\.github)\//.test(f) || /\.(md|sql|sh|py|mjs|ts|toml|yml|yaml)$/i.test(f) || /\.test\.js$/.test(f) || /(^|\/)\./.test(f)
    || /^(config\.prod\.js|config\.dev\.js|database-migration\.sql|site-manifest\.txt)$/.test(f));
  assert.deepEqual(bad, []);
  for (const e of M.exclude) assert.ok(!out.includes(e.path), e.path);
  assert.equal(out.length, listFiles(prodOut).length - 1);
});

test('the version stamp is applied and no placeholder is left in the development output', () => {
  for (const f of listFiles(devOut).filter((x) => x.endsWith('.html'))) assert.ok(!fs.readFileSync(path.join(devOut, f), 'utf8').includes('__ASSET_VERSION__'), f);
});

test('an unknown environment is refused', () => { const r = build({ out: tmp(), env: 'staging' }); assert.equal(r.ok, false); assert.match(r.errors[0], /unknown environment/); });

test('deploy-dev.yml builds the allowlisted dev site and publishes only _site (never the repository root)', () => {
  assert.match(WF, /node scripts\/build-site\.mjs --out _site --env dev --version "\$\{GITHUB_SHA::8\}"/);
  assert.match(WF, /publish_dir: _site\n/);
  assert.doesNotMatch(WF, /publish_dir: \.\s*$/m);
  assert.doesNotMatch(WF, /cp config\.dev\.js config\.js|rm -f CNAME|sed -i/);        // the old, root-publishing steps are gone
  assert.ok(WF.indexOf('build-site.mjs') < WF.indexOf('actions-gh-pages'), 'the build precedes the publish');
  assert.match(WF, /branches: \[dev\]/);                                                  // trigger unchanged
  assert.match(WF, /external_repository: Pintag-cyrora\/pintag-dev/);                    // target unchanged
  assert.match(WF, /peaceiris\/actions-gh-pages@[0-9a-f]{40}/);                          // still pinned to a commit
});

// ── CI path filters: every file that can change the production or development build must trigger the workflow that tests it ──
const CI = fs.readFileSync(path.join(ROOT, '.github/workflows/frontend-regression-tests.yml'), 'utf8');
function filterPaths(event) {
  const block = new RegExp(`\\n  ${event}:\\n(?:    .*\\n)*?    paths:\\n((?:      - .*\\n)+)`).exec(CI);
  assert.ok(block, `${event} has a paths filter`);
  return block[1].split('\n').filter(Boolean).map((l) => /^\s+- '([^']+)'/.exec(l)[1]);
}
const globToRe = (g) => new RegExp('^' + g.replace(/[.+^${}()|[\]\\]/g, '\\$&').replace(/\*\*/g, '\u0000').replace(/\*/g, '[^/]*').replace(/\u0000/g, '.*') + '$');
const matches = (patterns, file) => patterns.some((p) => globToRe(p).test(file));

test('path filters: every file the production or development build reads or publishes triggers the CI that tests it (push and pull request)', () => {
  const inputs = new Set([...M.include.map((e) => e.path), ...M.generated.map((g) => g.source), 'config.dev.js', 'config.prod.js', 'site-manifest.txt', 'scripts/build-site.mjs',
    '.github/workflows/deploy-dev.yml', '.github/workflows/deploy-prod.yml', 'site-allowlist.test.js', 'site-allowlist-dev.test.js', 'site-env-guard.test.js', 'site-build-refs.test.js']);
  for (const ev of ['push', 'pull_request']) {
    const pats = filterPaths(ev);
    const missing = [...inputs].filter((f) => !matches(pats, f));
    assert.deepEqual(missing, [], `${ev}: changes to these files would not trigger the build tests`);
  }
});

test('path filters stay narrow: only this workflow was widened, and no catch-all pattern was added', () => {
  for (const ev of ['push', 'pull_request']) {
    const pats = filterPaths(ev);
    assert.ok(!pats.some((p) => p === '**' || p === '*' || p === '**/*'), 'no catch-all');
    assert.ok(!matches(pats, 'docs/DEPLOYMENT_ALLOWLIST.md') && !matches(pats, 'PREVIEW.md') && !matches(pats, 'supabase/migrations/20261104000000_x.sql') && !matches(pats, 'scripts/seed-dev-lib.sh'), 'documentation, migrations and seed scripts do not trigger it');
  }
  assert.deepEqual(filterPaths('push'), filterPaths('pull_request'));
});

test('the path-filter matcher itself: single star stays inside a directory, double star crosses them', () => {
  assert.ok(matches(['*.png'], 'pintag-hero.png')); assert.ok(!matches(['*.png'], 'assets/pintag-watermark.png'));
  assert.ok(matches(['assets/**'], 'assets/pintag-watermark.png')); assert.ok(matches(['fonts/**'], 'fonts/a/b.woff2')); assert.ok(!matches(['fonts/**'], 'docs/fonts/x.woff2'));
});

test('the documentation records the dry-run finding for the pinned action and a verification procedure that never touches Pintag-dev', () => {
  const doc = fs.readFileSync(path.join(ROOT, 'docs/DEPLOYMENT_ALLOWLIST.md'), 'utf8');
  const pin = /peaceiris\/actions-gh-pages@([0-9a-f]{40})/.exec(WF)[1];
  assert.ok(doc.includes(pin), 'the documented commit is the pinned one');
  assert.match(doc, /There is no `dry_run` input/);
  for (const h of ['Prove the build without publishing', 'scratch target, never `Pintag-dev`', 'Before the first real publish', 'After the first real publish', 'Rollback']) assert.ok(doc.includes(h), h);
  assert.match(doc, /Environment guard/);
});
